"""Generate the local homing model from the exact selected host calibration."""
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'source/host'))
from arm_dynamics import Gravity
model=Gravity(identified=ROOT/'source/host/examples/profiles/gravity_selected.json')
joints=ET.parse(model.path).getroot().findall('joint')
assert len(joints)==6 and all(j.attrib['type']=='revolute' for j in joints)
assert all(np.allclose(np.fromstring(j.find('origin').attrib['rpy'],sep=' '),0) for j in joints)
assert list(model.model.parents)==[0,0,1,2,3,4,5]
arrays={'home_xyz':np.array([p.translation for p in model.model.jointPlacements[1:]]),
        'home_axis':np.array([np.fromstring(j.find('axis').attrib['xyz'],sep=' ') for j in joints]),
        'home_theta':model.theta.reshape(6,4)}
out=['/* Generated by tools/generate-home-model.py; selected hand model, no O6 data. */',
     '/* URDF SHA256: '+model.identity['urdf_sha256']+' */']
for name,a in arrays.items():
    out.append('static const float %s[%d][%d] = {'%(name,*a.shape))
    out.extend('    {'+', '.join(f'{float(x):.10e}f' for x in row)+'},' for row in a)
    out.append('};')
(ROOT/'source/src/homing/model_data.h').write_text('\n'.join(out)+'\n')
